struct ModeInfo
{
    std::uint8_t Transformed; // the endpoints after the first are deltas
    std::uint8_t PartitionBits;
    std::uint8_t EndpointBits;
    std::uint8_t DeltaBits[3];
};

/// One field of the endpoint bits: Count bits go to bit Shift of the end point Endpoint (0 to 3: the first and second end
/// point of the first subset, then of the second) of the channel Channel (0 red, 1 green, 2 blue).
struct Field
{
    std::uint8_t Channel;
    std::uint8_t Endpoint;
    std::uint8_t Count;
    std::uint8_t Shift;
};

