#!/usr/bin/env python3
"""Generate ../cpp/src/codecs/UnityTrees.inc from unity_trees.json (type trees of Texture2D, TextAsset, AudioClip and
Font harvested from real files; the driver uses them for serialized files whose trees were stripped)."""
import json, os
here = os.path.dirname(os.path.abspath(__file__))
trees = json.load(open(os.path.join(here, "unity_trees.json")))
dst = os.path.join(here, "../cpp/src/codecs/UnityTrees.inc")
out = ("// GENERATED by driver/tests/gen_unity_trees.py from unity_trees.json: do not edit.\n"
       "// Type trees of the objects the exporter reads, taken from real files; they stand in for the trees\n"
       "// stripped from the serialized files of release players (the layout must consume the whole object).\n"
       "// Class ID of the template I, then its nodes as 'level;type;name;size;flags,...'.\n")
out += "constexpr int TreeCountInc = %d;\n" % len(trees)
out += "constexpr int TreeClasses[TreeCountInc] = {%s};\n" % ", ".join(str(t["cls"]) for t in trees)
out += "const char *const TreeTexts[TreeCountInc] = {\n"
for t in trees:
    out += "    // class %d, serialized %s, Unity %s\n" % (t["cls"], t["serialized"], ", ".join(t["unity"]) or "?")
    nodes = ",".join("%d;%s;%s;%d;%d" % tuple(n) for n in t["tree"])
    chunks = [nodes[i:i + 100] for i in range(0, len(nodes), 100)]
    out += "\n".join('    "%s"' % c.replace("\\", "\\\\").replace('"', '\\"') for c in chunks) + ",\n"
out += "};\n"
open(dst, "w").write(out)
