"""Generate ../cpp/src/codecs/RomTables.inc from ../../data/rom-metadata/*/*.json (see FORMAT.md there). Only what the driver
uses is kept: per game the palettes of the compressed streams and the runs of uncompressed tiles with their palettes."""
import collections, glob, json, os
here = os.path.dirname(os.path.abspath(__file__))
dst = os.path.join(here, "../cpp/src/codecs/RomTables.inc")
GAP, MINIMUM = 512, 64   # raw runs closer than GAP bytes are joined; shorter runs than MINIMUM bytes are dropped

def merge(runs):
    """Runs of one format closer than GAP bytes are joined (their palettes added up); the two most used palettes stay"""
    out = []
    for r in sorted(runs, key=lambda r: (r["bpp"], r["offset"])):
        counts = collections.Counter()
        for p in r.get("palettes", []): counts["".join(p["colors"])] += p["count"]
        if out and out[-1][2] == r["bpp"] and r["offset"] - (out[-1][0] + out[-1][1]) <= GAP:
            out[-1][1] = r["offset"] + r["length"] - out[-1][0]; out[-1][3].update(counts)
        else:
            out.append([r["offset"], r["length"], r["bpp"], counts])
    return [r for r in out if r[1] >= MINIMUM]

def pal(p): return "".join(p["colors"])
games = []
for f in sorted(glob.glob(os.path.join(here, "../../data/rom-metadata/*/*.json"))):
    d = json.load(open(f))
    lines = ["%s %s" % (d["crc32"], d["console"])]
    for s in d["streams"]:
        pals = [pal(p) for p in s["palettes"][:3]]
        lines.append("S %s %d %s %s" % (s["codec"], s["offset"], ",".join(str(b) for b in s["bpp"]), " ".join(pals)))
    raw = d["rawPalettes"]
    lines.append("Q " + " ".join(pal(p) for p in raw[:6]))
    for o, n, b, pc in merge(d["rawTiles"]):
        lines.append("R %d %d %d %s" % (o, n, b, " ".join(k for k, _ in pc.most_common(2))))
    m = d.get("music")
    if m:   # how the game loads its music into the sound chip (see tools/rom-trace/spc_recipe.py)
        c = m["cpu"]
        lines.append("MC %d %d %d %d %d %d" % (c["pc"], c["a"], c["x"], c["y"], c["psw"], c["sp"]))
        lines.append("MD " + m["dsp"]); lines.append("MI " + m["io"])
        for b in m["engine"]: lines.append("ME %d %d %d" % (b["offset"], b["length"], b["dest"]))
        for p in m["patch"]: lines.append("MP %d %s" % (p["dest"], p["hex"]))
        for bank in m["banks"]:
            lines.append("MK")
            for b in bank["blocks"]: lines.append("MB %d %d %d" % (b["offset"], b["length"], b["dest"]))
            for sg in bank["songs"]: lines.append("MS %d %d %d %d" % tuple(sg))
    games.append((d["title"], "\n".join(lines)))
out = ("// GENERATED by driver/tests/gen_rom_tables.py from data/rom-metadata: do not edit.\n"
       "// Per known game (CRC-32 of the ROM): the palettes the screen used with the compressed streams (S lines: offset,\n"
       "// palettes), the palettes of the uncompressed graphics (Q) and the runs of those (R: offset, length, bits per pixel, the palettes it was drawn with).\n")
out += "constexpr int KnownGameCount = %d;\n" % len(games)
out += "const char *const KnownGameTexts[KnownGameCount] = {\n"
for title, text in games:
    out += "    // %s\n" % title.replace("\n", " ")
    chunks = [text[i:i + 100] for i in range(0, len(text), 100)]
    out += "\n".join('    "%s"' % c.replace("\n", "\\n") for c in chunks) + ",\n"
out += "};\n"
open(dst, "w").write(out)
print(len(games), "games,", len(out), "bytes")
