#!/usr/bin/env python3
"""Generates cpp/src/codecs/MixNames.data.inc from the list of file names of the Westwood MIX archives kept by
Dragon UnPACKer 5 (driver/data/mix_names.lst, from drv_default_mix.lst of v5 and based on the global mix database of
XCC Utilities): the names, one per line, zlib compressed, as a C array.
usage: gen_mix_names.py [lst] [out.inc]"""
import sys, os, zlib

here = os.path.dirname(os.path.abspath(__file__))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "../data/mix_names.lst")
out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(here, "../cpp/src/codecs/MixNames.data.inc")
names = []
for line in open(src, "rb").read().decode("latin-1").splitlines():
    line = line.strip()
    if line and not line.startswith("//"):
        names.append(line)
raw = "\n".join(names).encode("latin-1")
packed = zlib.compress(raw, 9)
with open(out, "w") as f:
    f.write("// GENERATED by tests/gen_mix_names.py: %d names, %d bytes unpacked\n" % (len(names), len(raw)))
    for i in range(0, len(packed), 24):
        f.write(", ".join("0x%02x" % b for b in packed[i:i + 24]) + ",\n")
print(len(names), "names", len(raw), "->", len(packed), "bytes")
sys.stdout.write("PackedSize=%d UnpackedSize=%d\n" % (len(packed), len(raw)))
